import {test,expect} from '@playwright/test';
import path from 'node:path';
import fs from 'node:fs';

test('Android-sized existing-video selection, recovery, test download and upload',async({page})=>{
 await page.setViewportSize({width:390,height:844});
 await page.goto('/');await page.getByLabel('Workspace role').selectOption('demo-citizen');await page.getByRole('button',{name:'Enter demonstration'}).click();
 await expect(page.getByRole('heading',{name:'Operations overview'})).toBeVisible();
 await page.goto('/capture');await page.getByRole('checkbox').check();
 await expect(page.getByRole('button',{name:'Choose existing video'})).toBeVisible();
 const picker=page.getByLabel('Choose evidence video');await expect(picker).not.toHaveAttribute('capture',/.*/);
 const fixture=path.resolve('.local/test-videos/SentinelAI-EN-02.mp4');
 await picker.setInputFiles(fixture);
 await expect.poll(()=>page.getByLabel('Selected video preview').evaluate((v:HTMLVideoElement)=>v.readyState)).toBeGreaterThan(0);
 await picker.setInputFiles({name:'invalid.txt',mimeType:'text/plain',buffer:Buffer.from('invalid')});
 await expect(page.getByText('Choose an MP4 video or WebM browser recording.')).toBeVisible();
 await expect(page.getByRole('button',{name:'Submit evidence'})).toBeDisabled();
 await expect(page.getByLabel('Selected video preview')).toHaveCount(0);
 await page.getByText('Fresh videos for testing',{exact:true}).click();
 const download=page.waitForEvent('download');await page.getByRole('link',{name:/EN-02/}).click();
 expect((await download).suggestedFilename()).toBe('SentinelAI-EN-02.mp4');
 await picker.setInputFiles(fixture);await page.getByLabel('Case title').fill('Fresh English phone file test');
 await page.getByLabel('Selected video preview').evaluate(async(v:HTMLVideoElement)=>{v.muted=true;await v.play();});
 await expect.poll(()=>page.getByLabel('Selected video preview').evaluate((v:HTMLVideoElement)=>v.currentTime)).toBeGreaterThan(.2);
 await page.getByLabel('Selected video preview').evaluate((v:HTMLVideoElement)=>v.pause());
 await expect(page.getByRole('button',{name:'Submit evidence'})).toBeEnabled();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy();
 fs.mkdirSync('.impeccable/review/screenshots',{recursive:true});
 await page.evaluate(()=>window.scrollTo(0,0));
 await page.screenshot({path:'.impeccable/review/screenshots/android-existing-video.png',fullPage:true});
 await page.setViewportSize({width:1440,height:1000});
 await page.evaluate(()=>window.scrollTo(0,0));
 await page.screenshot({path:'.impeccable/review/screenshots/desktop-existing-video.png',fullPage:true});
 await page.getByRole('button',{name:'Submit evidence'}).click();
 await expect(page.getByRole('heading',{name:'Fresh English phone file test',exact:true})).toBeVisible();
 await expect(page.getByText('Test recording',{exact:true})).toBeVisible();
 await expect(page.getByText('Partial analysis.',{exact:true})).toBeVisible({timeout:60000});
 const record=await(await page.request.get('/api/cases/'+page.url().split('/').pop())).json();
 expect(record.test_recording).toBe(1);expect(record.synthetic).toBe(0);
});
